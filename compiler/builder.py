"""Deterministic compiler: DeviceBundle -> SKILL.md, HOOKUP.md, cli_schema.json.

100% device-agnostic: every rendered line derives strictly from device.yaml and catalog.yaml.
Generated files MUST NEVER be hand-edited; ``--check`` fails CI on any drift.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from compiler.loader import load_bundle, validate_bundle
from core_types import DeviceBundle, ServiceSpec

MAX_SKILL_LINES = 80


class BuildDriftError(RuntimeError):
    """Raised under --check when generated outputs on disk diverge from YAML sources."""


@dataclass(frozen=True, slots=True)
class BuildResult:
    """Outcome of a bundle compilation or --check verification."""

    device_id: str
    output_dir: Path
    written_files: tuple[Path, ...]
    checked: bool


def _format_arg_signature(svc: ServiceSpec) -> str:
    parts: list[str] = []
    for arg in svc.args:
        suffix = "" if arg.required else "?"
        parts.append(f"{arg.name}{suffix}")
    return ", ".join(parts)


def _format_risk_tag(svc: ServiceSpec) -> str:
    short = svc.risk_class.value.split("_", 1)[0]
    tags: list[str] = [short]
    if svc.bypasses_action_lock:
        tags.append("lock-free")
    if svc.requires_confirm:
        tags.append("--confirm")
    elif svc.confirm_if:
        tags.append("conditional --confirm")
    return ", ".join(tags)


def render_skill_md(bundle: DeviceBundle) -> str:
    """Render concise 1-2 screen agent SKILL.md (omits expert_only services)."""
    dev = bundle.device
    default_services = bundle.catalog.default_agent_services()

    plugin_targets = [
        f"`{name}` (adapter `{prof.adapter_id}`)"
        for name, prof in dev.targets.items()
        if prof.adapter_id != "in_memory"
    ]
    has_non_fake_targets = bool(plugin_targets)
    has_in_memory = any(prof.adapter_id == "in_memory" for prof in dev.targets.values())

    description = f"Operate {' '.join(dev.display_name.split())} with the cli-device toolkit."
    lines: list[str] = [
        "---",
        f"name: {json.dumps(f'cli-device-{dev.device_id}', ensure_ascii=False)}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
        "---",
        "",
        f"<!-- DO NOT EDIT: generated by `cli-device bundle build {dev.device_id}` -->",
        f"# {dev.display_name} — Agent SKILL (`{dev.device_id}` v{dev.version})",
        "",
        "## 1. Prerequisites & Operating Rules",
        f"- Select bundle: `--bundle {dev.device_id}` "
        "(or `--bundle <bundle_dir>` / `CLI_DEVICE_BUNDLE`).",
        f"- Start daemon first: `cli-device-d --bundle {dev.device_id} "
        "--socket /tmp/cli-device-d.sock`.",
    ]
    if plugin_targets:
        lines.append(
            "- Targets needing an installed `cli_any_device.adapters` plugin before use: "
            + ", ".join(plugin_targets)
            + "."
        )
    if has_in_memory:
        lines.append(
            "- Built-in `--target in_memory` runs an offline in-memory fake "
            "(no physical actuation)."
        )
    if any(profile.is_real_hardware for profile in dev.targets.values()):
        lines.append(
            "- Live changes on real hardware require a verified bundle and daemon startup "
            "with `--allow-live-hardware`."
        )
    lines.extend(
        [
            "- Always pass `--json` and an explicit `--target <target>`.",
            "- Start every session with `sys detect` then `sys preflight`.",
            "- Run `--dry-run` before mutating sequences; pass `--confirm` only when authorized.",
            "- Use structured domain verbs instead of guessing raw coordinates or commands.",
        ]
    )
    if has_non_fake_targets:
        lines.append(
            "- On hardware/simulator targets (not `in_memory`), commands wait for supervisor "
            f"completion: {dev.hookup.completion_semantics}"
        )
    else:
        lines.append(
            "- Completion semantics: offline in-memory simulation only "
            "(no physical hardware attached)."
        )

    lines.extend(
        [
            "",
            "## 2. Atomic Service Catalog",
            "```text",
        ]
    )
    catalog_start = len(lines)
    lines.extend(
        [
            "```",
            "",
            "## 3. Standard Agent Loop",
            f"1. `cli-device --bundle {dev.device_id} --json --target <target> sys detect`",
            f"2. `cli-device --bundle {dev.device_id} --json --target <target> sys preflight`",
            f"3. `cli-device --bundle {dev.device_id} --json --target <target> "
            "--dry-run <group> <verb> [args...]`",
            "4. Execute live (with `--confirm` when required) and inspect `.ok` and `.error.step`.",
            "",
            "## 4. Fault & Emergency-Stop Protocol",
            "- Exit codes: `0`=ok/dry-run, `1`=exec fault (fail-safe applied),",
            "  `2`=usage/capability, `3`=safety denied (zero actuation),",
            "  `4`=needs `--confirm`, `5`=timeout, `99`=e-stop latched.",
            "- On non-zero exit, do NOT blindly retry R3 commands: run `sys status` first.",
            f"- Software halt: `cli-device --bundle {dev.device_id} --json "
            "--target <target> sys abort` (lock-free).",
            f"- E-stop policy: {dev.hookup.estop_policy}",
        ]
    )

    catalog_lines = []
    for svc in default_services:
        sig = f"{svc.name}({_format_arg_signature(svc)})"
        ret = svc.returns_summary or "ok"
        tag = _format_risk_tag(svc)
        catalog_lines.append(f"{sig:<38} -> {ret:<26} [{tag}]")
    catalog_capacity = MAX_SKILL_LINES - len(lines)
    if len(catalog_lines) > catalog_capacity:
        catalog_lines = catalog_lines[: catalog_capacity - 1]
        catalog_lines.append(
            f"More commands: cli-device --bundle {dev.device_id} --help"
        )
    lines[catalog_start:catalog_start] = catalog_lines
    return "\n".join(" ".join(line.splitlines()) for line in lines) + "\n"


def render_hookup_md(bundle: DeviceBundle) -> str:
    """Render human wiring, pre-flight, safety, and troubleshooting manual (HOOKUP.md)."""
    dev = bundle.device
    hk = dev.hookup

    lines: list[str] = [
        f"<!-- DO NOT EDIT: generated by `cli-device bundle build {dev.device_id}` -->",
        f"# {dev.display_name} — Human Hookup & Pre-Flight Manual (`{dev.device_id}`)",
        "",
        f"- **Device ID:** `{dev.device_id}` (`{dev.device_kind}`, version `{dev.version}`)",
        f"- **Review Status:** `{dev.review_status}`",
        f"- **Primary Interface:** {hk.primary_interface}",
        f"- **Default Endpoint:** `{hk.default_endpoint}`",
    ]
    if hk.host_ip:
        lines.append(f"- **Host Static IP / Mask:** `{hk.host_ip}` / `{hk.subnet_mask}`")
    lines.extend(
        [
            f"- **Fallback Interface:** {hk.fallback_interface}",
            "",
            "## Completion Semantics",
            hk.completion_semantics,
            "",
            "## Emergency Stop Policy (Physical E-Stop Mandatory)",
            hk.estop_policy,
            "",
            "## Pre-Flight Prohibitions",
        ]
    )
    for item in hk.preflight_prohibitions:
        lines.append(f"- {item}")

    lines.extend(["", "## Field Verification Checklist (Required Before Live Hardware Use)"])
    for item in hk.field_verification_required:
        lines.append(f"- [ ] {item}")

    if dev.axes:
        lines.extend(
            [
                "",
                "## Declared Axis Limits",
                "| Axis | Min (mm) | Max (mm) | Site Verified | Source |",
                "|---|---:|---:|---|---|",
            ]
        )
        for ax in dev.axes.values():
            lines.append(
                f"| `{ax.name}` | {ax.min_mm:g} | {ax.max_mm:g} | "
                f"{'yes' if ax.verified else 'NO'} | {ax.source} |"
            )

    if dev.safety_limits:
        lines.extend(
            [
                "",
                "## Declared Safety Limits",
                "| Parameter | Min | Max | Unit | Site Verified | Source |",
                "|---|---:|---:|---|---|---|",
            ]
        )
        for lim in dev.safety_limits.values():
            lines.append(
                f"| `{lim.name}` | {lim.min_value:g} | {lim.max_value:g} | {lim.unit} | "
                f"{'yes' if lim.verified else 'NO'} | {lim.source} |"
            )

    lines.extend(
        [
            "",
            "## Target Profiles & Capabilities",
            "| Target | Adapter | Real Hardware | Capabilities | Notes |",
            "|---|---|---|---|---|",
        ]
    )
    for target in dev.targets.values():
        caps = ", ".join(sorted(target.capabilities))
        lines.append(
            f"| `{target.name}` | `{target.adapter_id}` | "
            f"{'YES' if target.is_real_hardware else 'no'} | `{caps}` | {target.notes} |"
        )

    for sec in hk.sections:
        lines.extend(
            [
                "",
                f'<a id="{sec.section_id}"></a>',
                f"## {sec.title}",
                sec.summary,
                "",
            ]
        )
        for idx, step in enumerate(sec.steps, start=1):
            lines.append(f"{idx}. {step}")

    lines.append("")
    return "\n".join(lines)


def render_cli_schema(bundle: DeviceBundle) -> dict[str, Any]:
    """Render machine-readable CLI schema consumed by the thin ``cli-device`` frontend."""
    dev = bundle.device
    services_payload: list[dict[str, Any]] = []
    for svc in bundle.catalog.services.values():
        services_payload.append(
            {
                "name": svc.name,
                "cli_group": svc.cli_group,
                "cli_command": svc.cli_command,
                "summary": svc.summary,
                "returns_summary": svc.returns_summary,
                "risk_class": svc.risk_class.value,
                "requires_confirm": svc.requires_confirm,
                **({"confirm_if": list(svc.confirm_if)} if svc.confirm_if else {}),
                "bypasses_action_lock": svc.bypasses_action_lock,
                "expert_only": svc.expert_only,
                "requires_capabilities": sorted(svc.requires_capabilities),
                "timeout_s": svc.timeout_s,
                "args": [
                    {
                        "name": a.name,
                        "type": a.arg_type,
                        "required": a.required,
                        "unit": a.unit,
                        "min_value": a.min_value,
                        "max_value": a.max_value,
                        "default": a.default,
                        "description": a.description,
                    }
                    for a in svc.args
                ],
            }
        )

    return {
        "generated_by": f"cli-device bundle build {dev.device_id}",
        "device_id": dev.device_id,
        "display_name": dev.display_name,
        "device_kind": dev.device_kind,
        "version": dev.version,
        "review_status": dev.review_status,
        "targets": {
            name: {
                "adapter_id": prof.adapter_id,
                "is_real_hardware": prof.is_real_hardware,
                "default_endpoint": prof.default_endpoint,
                "capabilities": sorted(prof.capabilities),
                "require_confirm_for_risks": sorted(
                    r.value for r in prof.require_confirm_for_risks
                ),
            }
            for name, prof in dev.targets.items()
        },
        "services": services_payload,
    }


def build_bundle(bundle_dir: Path, output_dir: Path, *, check: bool = False) -> BuildResult:
    """Validate bundle YAML and compile (or verify with ``--check``) SKILL/HOOKUP/cli_schema."""
    bundle = load_bundle(bundle_dir)
    validate_bundle(bundle)

    expected_files: dict[Path, str] = {
        output_dir / "SKILL.md": render_skill_md(bundle),
        output_dir / "HOOKUP.md": render_hookup_md(bundle),
        output_dir / "cli_schema.json": json.dumps(render_cli_schema(bundle), indent=2) + "\n",
    }

    if check:
        drifted: list[str] = []
        for path, expected in expected_files.items():
            if not path.exists():
                drifted.append(f"Missing generated file: {path}")
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != expected:
                drifted.append(f"Drift detected in generated file: {path}")
        if drifted:
            raise BuildDriftError("\n".join(drifted))
        return BuildResult(
            device_id=bundle.device.device_id,
            output_dir=output_dir,
            written_files=tuple(expected_files.keys()),
            checked=True,
        )

    output_dir.mkdir(parents=True, exist_ok=True)
    for path, content in expected_files.items():
        path.write_text(content, encoding="utf-8")
    return BuildResult(
        device_id=bundle.device.device_id,
        output_dir=output_dir,
        written_files=tuple(expected_files.keys()),
        checked=False,
    )
